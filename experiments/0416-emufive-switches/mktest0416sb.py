#!/usr/bin/env python3
"""BC5 experiment 0416: the test the box runs could not give (Codex, 2026-11-12 22:20 UTC): set-buffer with a forced
a4 = -1, on a mapped and on an unmapped target, with the map opt-in off and on, and the guard's refusal checked.
In the private build the title's leftover a4 was never -1, so no start reached these branches.

It cuts the real functions, as written, out of the edited src/libs/libAmpr.cpp (mk0416x.py's output):
SetBufferIsMapFlavour, Bc5SetBufferGuardOn, Bc5SetBufferTargetMapped, Bc5SetBufferMapAllowed and
CommandBufferSetBuffer, and compiles them with stand-ins for what they call: the kernel's virtual query (a table of
committed and reserved ranges), ExecuteAmmMapCommand (records the map it was asked for and maps nothing), and the
command-buffer header helpers (a real 64-byte header in the test's memory). Nothing of the emulator runs.

The switches are read once per process, so the binary is run four times; it reads the same environment to know what
to expect. Calls in every run (va 0x300a827a0 len 0x400 is ASTRO BOT's call of exp 0413; a3 != va everywhere but E):
  A  a4 = 0xffffffffffffffff, target committed      B  a4 = 0xffffffff, target committed
  C  a4 = -1, nothing at the target                 D  a4 = -1, target reserved but not committed
  E  a4 = -1 but a3 == va (the buffer flavour)      F  a4 = 0x9088e4e98 (the leftover of the private build)
Expected:
  guard on,  map off (the default)   no map at all; A-F attach the buffer; exp 0413's line for A and B, exp 0416's
                                      line for C and D
  guard on,  KYTY_BC5_AMM_SETBUFFER_MAP=1   A and B refused by the guard (attach, exp 0413's line); C and D map
                                      0x300a80000 + 0x4000 with CPU and GPU read/write; no exp 0416 line
  KYTY_BC5_AMM_SETBUFFER_GUARD=0, map off   no map; exp 0416's line for A-D (the opt-in alone also stops the bug)
  guard 0, map 1                      A-D all map: exp 0413's bug as it was, kept reachable only by two switches
E and F attach in every run and never print a line.
usage: mktest0416sb.py <edited libAmpr.cpp> <out test .cpp>"""
import sys

s = open(sys.argv[1], "rb").read().replace(b"\r\n", b"\n").decode("utf-8")


def cut(start, end="\n}\n"):
    a = s.index(start)
    return s[a:s.index(end, a) + len(end)]


body = "\n".join(cut(sig) for sig in (
    "static bool SetBufferIsMapFlavour(uint64_t va, uint64_t a3, uint64_t a4) {",
    "static bool Bc5SetBufferGuardOn() {",
    "static bool Bc5SetBufferTargetMapped(uint64_t cb, uint64_t va, uint32_t size, uint64_t a3, uint64_t a4, uint64_t a5) {",
    "static bool Bc5SetBufferMapAllowed(uint64_t cb, uint64_t va, uint32_t size, uint64_t a3, uint64_t a4, uint64_t a5) {",
    "static int KYTY_SYSV_ABI CommandBufferSetBuffer(void* command_buffer, void* buffer, uint32_t size,"))
assert "Bc5SetBufferMapAllowed(reinterpret_cast<uint64_t>(command_buffer)" in body and "ExecuteAmmMapCommand(command)" in body

PRE = r'''// Generated by experiments/0416-emufive-switches/mktest0416sb.py: do not edit. GPL-2.0-only.
#include <cinttypes>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>
#include <vector>

#define KYTY_SYSV_ABI
#define PRINT_NAME()
static constexpr int OK = 0;
namespace LibKernel {
static constexpr int KERNEL_ERROR_EINVAL = -2147352554, KERNEL_ERROR_EFAULT = -2147352562, KERNEL_ERROR_EBUSY = -2147352560;
namespace Memory {
struct VirtualQueryInfo { // the fields of src/kernel/memory.h that the unit reads
	uintptr_t start;
	uintptr_t end;
	uint32_t  is_committed : 1;
};
struct Range { uint64_t start, end; bool committed; };
static std::vector<Range> g_ranges;
static int KernelVirtualQuery(const void* addr, int, VirtualQueryInfo* info, size_t) {
	const auto a = reinterpret_cast<uint64_t>(addr);
	for (const auto& r: g_ranges) {
		if (a >= r.start && a < r.end) { info->start = r.start; info->end = r.end; info->is_committed = r.committed ? 1 : 0; return OK; }
	}
	return KERNEL_ERROR_EINVAL - 1; // "no such mapping"
}
} // namespace Memory
} // namespace LibKernel
static bool AmmTrace() { return false; }
static void AmmTraceStamp() {}
constexpr uint64_t COMMAND_BUFFER_NUM_OFFSET = 0x08, COMMAND_BUFFER_DATA_OFFSET = 0x10, AMM_PAGE_SIZE = 0x4000;
constexpr uint32_t COMMAND_BUFFER_SIZE_MAX = 64 * 1024 * 1024;
constexpr int      PROT_CPU_READ = 0x01, PROT_CPU_WRITE = 0x02, PROT_GPU_READ = 0x10, PROT_GPU_WRITE = 0x20;
enum class AmmCommandKind : uint32_t { MapAuto, MapDirect, Unmap };
struct CommandBufferState {
	struct AmmMapCommand {
		uint64_t       record_offset = 0;
		AmmCommandKind kind          = AmmCommandKind::MapAuto;
		uint64_t       va            = 0;
		uint64_t       dmem_offset   = 0;
		uint64_t       size          = 0;
		int32_t        type          = 0;
		int32_t        prot          = 0;
	};
};
static std::vector<CommandBufferState::AmmMapCommand> g_maps;    // what the map flavour asked for
static std::vector<uint64_t>                          g_attached; // buffers attached by the buffer flavour
static int  ExecuteAmmMapCommand(const CommandBufferState::AmmMapCommand& command) { g_maps.push_back(command); return OK; }
static bool ValidateCommandBufferHeader(uint64_t) { return true; }
template <class T> static T ReadCommandBufferUnchecked(uint64_t addr) { T v; std::memcpy(&v, reinterpret_cast<void*>(addr), sizeof(T)); return v; }
template <class T> static void WriteCommandBufferUnchecked(uint64_t addr, T v) { std::memcpy(reinterpret_cast<void*>(addr), &v, sizeof(T)); }
static bool WriteCommandBufferPointers(uint64_t cb, uint64_t buffer, uint32_t) {
	WriteCommandBufferUnchecked(cb + COMMAND_BUFFER_DATA_OFFSET, buffer);
	g_attached.push_back(buffer);
	return true;
}
'''

POST = r'''
static int g_fail = 0;
#define CHECK(c, ...) do { if (!(c)) { g_fail++; std::printf("FAIL line %d: ", __LINE__); std::printf(__VA_ARGS__); std::printf("\n"); } } while (0)

static bool env_on(const char* name, bool unset) {
	const char* e = std::getenv(name);
	return e == nullptr ? unset : (e[0] != '\0' && std::strcmp(e, "0") != 0);
}
static int count(const std::string& hay, const char* needle) {
	int n = 0;
	for (size_t p = hay.find(needle); p != std::string::npos; p = hay.find(needle, p + 1)) n++;
	return n;
}

struct Call { const char* name; uint64_t va; uint32_t len; uint64_t a3, a4; };

int main(int argc, char** argv) {
	const bool guard = env_on("KYTY_BC5_AMM_SETBUFFER_GUARD", true);
	const bool map   = env_on("KYTY_BC5_AMM_SETBUFFER_MAP", false);
	const char* errfile = argc > 1 ? argv[1] : "sb0416.err";
	std::printf("guard %s, map opt-in %s\n", guard ? "on" : "off", map ? "on" : "off");
	if (std::freopen(errfile, "w", stderr) == nullptr) { std::printf("FAIL: cannot redirect stderr\n"); return 2; }

	using LibKernel::Memory::g_ranges;
	g_ranges.push_back({0x300a80000ull, 0x300a84000ull, true});  // ASTRO BOT's heap page of exp 0413: committed
	g_ranges.push_back({0x500000000ull, 0x500010000ull, false}); // reserved, not committed
	const Call calls[] = {
	    {"A", 0x300a827a0ull, 0x400, 0x300a82be0ull, ~0ull},
	    {"B", 0x300a827a0ull, 0x400, 0x300a82be0ull, 0xffffffffull},
	    {"C", 0x700001230ull, 0x10000, 0x1ull, ~0ull},
	    {"D", 0x500000000ull, 0x400, 0x2ull, ~0ull},
	    {"E", 0x300a827a0ull, 0x400, 0x300a827a0ull, ~0ull},
	    {"F", 0x300a827a0ull, 0x400, 0x300a82be0ull, 0x9088e4e98ull},
	};
	for (const auto& c: calls) {
		alignas(16) unsigned char header[64] = {};
		const size_t maps = g_maps.size(), att = g_attached.size();
		const int    r    = CommandBufferSetBuffer(header, reinterpret_cast<void*>(c.va), c.len, c.a3, c.a4, 0);
		const bool mapped_target = c.name[0] == 'A' || c.name[0] == 'B';
		const bool signature     = c.name[0] >= 'A' && c.name[0] <= 'D';
		const bool want_map      = signature && map && !(guard && mapped_target);
		CHECK(r == OK, "%s returned 0x%x", c.name, static_cast<unsigned>(r));
		if (want_map) {
			CHECK(g_maps.size() == maps + 1 && g_attached.size() == att, "%s: want one map and no attach (maps +%zu, attached +%zu)", c.name, g_maps.size() - maps, g_attached.size() - att);
			if (g_maps.size() == maps + 1) {
				const auto&    m    = g_maps.back();
				const uint64_t va   = c.va & ~0x3fffull;
				const uint64_t size = ((c.va + c.len + 0x3fffull) & ~0x3fffull) - va;
				CHECK(m.kind == AmmCommandKind::MapAuto && m.va == va && m.size == size && m.prot == 0x33 && m.type == 0,
				      "%s: map va 0x%" PRIx64 " size 0x%" PRIx64 " prot 0x%x, want 0x%" PRIx64 " 0x%" PRIx64 " 0x33", c.name, m.va, m.size, m.prot, va, size);
			}
			uint64_t data = 1;
			std::memcpy(&data, header + COMMAND_BUFFER_DATA_OFFSET, 8);
			CHECK(data == 0, "%s: the map flavour must leave the header alone", c.name);
		} else {
			CHECK(g_maps.size() == maps, "%s: NOTHING may be mapped (maps +%zu)", c.name, g_maps.size() - maps);
			CHECK(g_attached.size() == att + 1 && g_attached.back() == c.va, "%s: want the buffer attached", c.name);
		}
		std::printf("%s: a4 0x%" PRIx64 " -> %s\n", c.name, c.a4, g_maps.size() > maps ? "mapped" : "attached, nothing mapped");
	}
	// the 17th and later refusals print nothing (told < 16), and still refuse
	const size_t maps = g_maps.size();
	for (int i = 0; i < 40; i++) {
		alignas(16) unsigned char header[64] = {};
		CommandBufferSetBuffer(header, reinterpret_cast<void*>(0x300a827a0ull), 0x400, 0x300a82be0ull, ~0ull, 0);
	}
	const bool repeat_maps = map && !guard;
	CHECK(g_maps.size() == maps + (repeat_maps ? 40u : 0u), "40 more calls like A: maps +%zu", g_maps.size() - maps);

	std::fflush(stderr);
	std::string err;
	if (FILE* f = std::fopen(errfile, "rb")) { char buf[4096]; size_t n; while ((n = std::fread(buf, 1, sizeof(buf), f)) > 0) err.append(buf, n); std::fclose(f); }
	const int l13 = count(err, "exp 0413: set-buffer with the map signature on mapped memory");
	const int l16 = count(err, "exp 0416: set-buffer with the map signature on a target that is not mapped");
	const int want13 = guard ? 16 : 0;                 // A, B and 14 of the 40 repeats
	const int want16 = map ? 0 : (guard ? 2 : 16);     // C and D; without the guard A-D and 12 repeats
	CHECK(l13 == want13, "exp 0413 lines: %d, want %d", l13, want13);
	CHECK(l16 == want16, "exp 0416 lines: %d, want %d", l16, want16);
	CHECK(count(err, "KYTY_BC5_AMM_SETBUFFER_GUARD on") == (guard ? 1 : 0) && count(err, "KYTY_BC5_AMM_SETBUFFER_GUARD off") == (guard ? 0 : 1), "the guard's own on/off line");
	if (guard) CHECK(count(err, "va 0x0000000300a827a0 len 0x400 a3 0x300a82be0 a4 0xffffffffffffffff") >= 1, "the refusal names the call");
	std::printf("lines: exp 0413 %d, exp 0416 %d; maps %zu, attached %zu\n", l13, l16, g_maps.size(), g_attached.size());
	std::printf("%s: %d failed checks\n", g_fail == 0 ? "PASS" : "FAIL", g_fail);
	return g_fail == 0 ? 0 : 1;
}
'''
open(sys.argv[2], "w", encoding="utf-8", newline="\n").write(PRE + "\n" + body + POST)
print("ok")
