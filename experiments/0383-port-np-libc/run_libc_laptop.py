"""PORT-LIBC on the laptop: LibcNidTests against the InitLibcInternal_1 block of one version of the real libC.cpp.

usage: run_libc_laptop.py <label> <host tree> <out dir>

The tree has no submodules here, so libC.cpp as a whole does not compile. This script cuts `namespace LibcInternal`
(the wrappers and the registration table, byte for byte) out of the tree's src/libs/libC.cpp, adds stand-ins for the
few things outside it, and builds that with the real src/loader/symbolDatabase.cpp, the real common/abi.h and
laptop-shim/. Compiler: VS 18's LLVM, so KYTY_SYSV_ABI is the real attribute. It is a laptop check of the table and the
wrappers, not the host link: that is the box plan in README.md.
"""
import os
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
LLVM = pathlib.Path(r"C:\Program Files\Microsoft Visual Studio\18\Community\VC\Tools\Llvm\x64")
CLANG = LLVM / "bin" / "clang++.exe"
os.environ["PATH"] = str(LLVM / "lib" / "clang" / "22" / "lib" / "windows") + os.pathsep + os.environ["PATH"]

PRELUDE = """// generated by run_libc_laptop.py: stand-ins, then the real namespace LibcInternal of libC.cpp
#include "common/abi.h"
#include "common/assert.h"
#include "common/common.h"
#include "common/logging/log.h"
#include "libs/libs.h"
#include "loader/symbolDatabase.h"
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#define VA_ARGS void* unused_args
#define VA_CONTEXT(ctx) int ctx = 0
namespace Libs {
struct VaList;
using GuestVprintf = int (*)(const char*, VaList*);
using GuestSnprintf = int (*)(int*);
static int StandInVprintf(const char*, VaList*) { return 0; }
static int StandInSnprintf(int*) { return 0; }
static GuestVprintf GetGuestVprintfFunc() { return StandInVprintf; }
static GuestSnprintf GetGuestSnprintfCtxFunc() { return StandInSnprintf; }
namespace LibcInternalExt {
LIB_DEFINE(InitLibcInternalExt_1) { (void)s; }
static int KYTY_SYSV_ABI LibcInternalForceTlsDestructor(int) { return 0; }
static void KYTY_SYSV_ABI LibcInternalFinalizeTls() {}
} // namespace LibcInternalExt
namespace LibC {
static void KYTY_SYSV_ABI abort() {}
static int KYTY_SYSV_ABI cxa_atexit() { return 0; }
static void KYTY_SYSV_ABI cxa_finalize() {}
static int KYTY_SYSV_ABI std_execute_once() { return 0; }
} // namespace LibC
"""


def run(args, out, **kw):
    r = subprocess.run(args, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, errors="replace", **kw)
    out.write_text(r.stdout, encoding="utf-8")
    return r.returncode, r.stdout


def main():
    label, host, out = sys.argv[1:4]
    host = pathlib.Path(host)
    out = pathlib.Path(out)
    out.mkdir(parents=True, exist_ok=True)
    source = (host / "src" / "libs" / "libC.cpp").read_bytes().decode("utf-8")
    m = re.search(r"^namespace LibcInternal \{\n.*?^\} // namespace LibcInternal\n", source, re.S | re.M)
    assert m is not None, "no namespace LibcInternal block"
    assert 'LIB_DEFINE(InitLibcInternal_1)' in m.group(0)
    slice_cpp = out / f"libc-slice-{label}.cpp"
    slice_cpp.write_bytes((PRELUDE + m.group(0) + "} // namespace Libs\n").encode("utf-8"))
    exe = out / f"LibcNidTests-{label}.exe"
    flags = ["-std=c++20", "-O1", "-g", "-fsanitize=address", "-Wall", "-Wextra", "-Wno-unused-function",
             "-Wno-unused-parameter", "-Wno-unused-variable", "-Wno-deprecated-declarations", "-Wno-macro-redefined",
             "-Wno-builtin-requires-header", "-Wno-incompatible-library-redeclaration", "-fno-builtin",
             "-DBC5_LAPTOP_SLICE", "-D_CRT_SECURE_NO_WARNINGS", "-I", str(HERE / "laptop-shim"), "-I", str(host / "src")]
    rc, text = run([str(CLANG), *flags, str(HERE / "LibcNidTests.cpp"), str(slice_cpp),
                    str(host / "src" / "loader" / "symbolDatabase.cpp"), "-o", str(exe)], out / f"{label}-build.txt")
    print(f"{label}: build rc={rc}")
    if rc != 0:
        print(text[:4000])
        return 3
    rc, text = run([str(exe)], out / f"{label}-run.txt", timeout=60)
    print(text)
    print(f"{label}: run rc={rc}")
    return rc


if __name__ == "__main__":
    sys.exit(main())
