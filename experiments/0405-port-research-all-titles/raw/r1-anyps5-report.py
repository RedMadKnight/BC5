# r1-anyps5-report.py -- per-library tables and the missing-export TSV from r1-anyps5-inventory.py's JSON
# and r1-anyps5-loaded.py's JSON (which of our registrations InitAll actually loads).
# Usage: python -I r1-anyps5-report.py <inv.json> <loaded.json> <AnyPS5 root> <out dir> [--commits]
# Writes <out>/r1-anyps5-missing.tsv, <out>/_work/libtable.tsv, <out>/_work/nothosted.tsv and, with --commits,
# <out>/_work/commits/<lib>.txt (non-merge commits after the port point touching core/libs/prx/<lib>).
import json, os, sys, subprocess, collections

inv, loaded, any_root, outdir = sys.argv[1:5]
d = json.load(open(inv))
ld = json.load(open(loaded))
live = set(ld['live'])
dead_where = ld['dead_where']
ours = d['ours']

def norm(x):
    x = x.lower().replace('_native', '.native')
    return x[6:] if x.startswith('libsce') else x

our_names = {norm(x) for x in d['our_libs'] + d['our_mods']}
# AnyPS5 module -> our LIB_VERSION name where the names differ (each checked by NID overlap)
ALIAS = {
    'libSceCesCs': 'Ces', 'libSceAgc': 'Graphics5', 'libSceAgcDriver': 'Graphics5Driver',
    'libSceAgcVsh': 'Graphics5', 'libScePsml_debug': 'Psml', 'libSceVideoRecordingP': 'libSceVideoRecording',
    'libSceAddressSanitizer': 'DbgAddressSanitizer', 'libSceGnmDriverForNeoMode': 'libSceGnmDriver',
    'libkernel_sys': 'libkernel', 'libSceAjm.native': 'Ajm', 'libSceAudiodec.native': 'Audiodec',
    'libSceAppContent': 'AppContent', 'libSceNgs2.native': 'Ngs2', 'libSceNpTrophy2': 'NpTrophy2',
}
hosted = {}
for l in d['lib']:
    if l in ALIAS: hosted[l] = ALIAS[l]; continue
    n = norm(l)
    if n in our_names: hosted[l] = n
    elif n.endswith('.native') and n[:-7] in our_names: hosted[l] = n[:-7]

os.makedirs(os.path.join(outdir, '_work'), exist_ok=True)
tsv = open(os.path.join(outdir, 'r1-anyps5-missing.tsv'), 'w', newline='\n', encoding='utf-8')
tsv.write('# AnyPS5 4f41f4c37 exports (core/libs/prx; exported functions, APS5_EXPORT/asm aliases and extern "C" data)\n'
          '# of the libraries we host whose NID our effective tree (KytyPlus f266548 + patch 0001, e4) does not export\n'
          '# at run time: no LIB_FUNC/LIB_OBJECT reachable from Libs::InitAll. our_unloaded_table = where the NID is\n'
          '# registered in a table InitAll never loads (r1-anyps5-loaded.py), else "-".\n'
          '# implemented: yes = body is not the NotImplemented_nid_no_patch stub. kind: const = no call and <= 3\n'
          '# statements (returns a code / writes a constant), logic = anything else, data = exported variable.\n'
          '# body = body lines. Generated by r1-anyps5-inventory.py, r1-anyps5-loaded.py, r1-anyps5-report.py.\n')
tsv.write('library\tnid\tname\tanyps5_file_line\timplemented\tkind\tbody\tour_unloaded_table\n')
rows = []
for l in sorted(hosted):
    e = d['lib'][l]
    impl = {k: v for k, v in e.items() if v['kind'] != 'pending'}
    inlive = [k for k in e if k in live]
    indead = [k for k in e if k in ours and k not in live]
    miss = {k: v for k, v in e.items() if k not in live}
    imiss = {k: v for k, v in impl.items() if k not in live}
    for k, v in sorted(miss.items(), key=lambda kv: (kv[1]['kind'] == 'pending', kv[1]['file'], kv[1]['line'])):
        tsv.write('%s\t%s\t%s\t%s:%d\t%s\t%s\t%d\t%s\n' % (
            l, k, v['name'], v['file'].replace('core/libs/prx/', ''), v['line'],
            'no' if v['kind'] == 'pending' else 'yes', v['kind'], v['body_lines'],
            dead_where[k][0] if k in dead_where else '-'))
    kinds = collections.Counter(v['kind'] for v in imiss.values())
    body = sum(v['body_lines'] for v in imiss.values() if v['kind'] == 'logic')
    rows.append(dict(lib=l, ours=hosted[l], exports=len(e), impl=len(impl), live=len(inlive), dead=len(indead),
                     impl_missing=len(imiss), impl_missing_dead=sum(1 for k in imiss if k in ours),
                     const=kinds['const'], data=kinds['data'], logic=kinds['logic'], logic_lines=body,
                     pending_missing=len(miss) - len(imiss)))
tsv.close()
cols = ['lib', 'ours', 'exports', 'impl', 'live', 'dead', 'impl_missing', 'impl_missing_dead', 'const', 'data', 'logic',
        'logic_lines', 'pending_missing']
with open(os.path.join(outdir, '_work', 'libtable.tsv'), 'w', newline='\n') as f:
    f.write('\t'.join(cols) + '\n')
    for r in sorted(rows, key=lambda r: -r['impl_missing']): f.write('\t'.join(str(r[c]) for c in cols) + '\n')
print('hosted libs', len(rows), {c: sum(r[c] for r in rows) for c in cols[2:]})
nh = [(l, len(e), sum(1 for v in e.values() if v['kind'] != 'pending')) for l, e in d['lib'].items() if l not in hosted]
print('not hosted libs', len(nh), 'exports', sum(x[1] for x in nh), 'impl', sum(x[2] for x in nh))
with open(os.path.join(outdir, '_work', 'nothosted.tsv'), 'w', newline='\n') as f:
    for x in sorted(nh, key=lambda x: -x[2]): f.write('%s\t%d\t%d\n' % x)

if '--commits' in sys.argv:
    os.makedirs(os.path.join(outdir, '_work', 'commits'), exist_ok=True)
    env = dict(os.environ, GIT_NO_LAZY_FETCH='1')
    for l in sorted(hosted):
        base = '27c88a8' if l == 'libSceNpCppWebApi' else '7ba97f4'
        out = subprocess.run(['git', '-C', any_root, 'log', '--no-merges', '--no-renames', '--date=short',
                              '--format=%h %ad %s', base + '..4f41f4c37', '--', 'core/libs/prx/' + l],
                             capture_output=True, text=True, env=env, encoding='utf-8', errors='replace').stdout
        if out.strip():
            open(os.path.join(outdir, '_work', 'commits', l + '.txt'), 'w', newline='\n').write(out)
