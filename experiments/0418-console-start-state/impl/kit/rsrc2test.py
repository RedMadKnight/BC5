import sys

# Builds a runnable test of exp 0418's rsrc2_journal, cut out of the unit as it is: stand-ins for BC5_DIAG_ENV,
# Mapping and covered_sorted (true: the test's memory is the host's own), then synthetic buffers.
# usage: rsrc2test.py <bc5LleAgc.cpp> <out.cpp>
src = open(sys.argv[1], "rb").read().decode("utf-8")
a = src.index("#ifndef BC5_LEAN\n// Experiment 0418 result 4")
b = src.index("#endif // BC5_LEAN\n", a) + len("#endif // BC5_LEAN\n")
body = src[a:b]
out = r'''// generated by rsrc2test.py: a test of rsrc2_journal only
#include "bc5/gc_trace.hpp"
#include <cinttypes>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <mutex>
#include <set>
#include <string>
#include <vector>
#define BC5_DIAG_ENV(name) std::getenv(name)
namespace bc5::direct { struct Mapping {}; }
static bool covered_sorted(const std::vector<bc5::direct::Mapping>&, uint64_t a, uint64_t) { return a != 0; }
''' + body + r'''
static void put_addr(std::vector<uint32_t>& ib, const void* p) {
	const uint64_t a = reinterpret_cast<uint64_t>(p);
	ib.push_back(static_cast<uint32_t>(a));
	ib.push_back(static_cast<uint32_t>(a >> 32u));
}
int main() {
#ifdef _WIN32
	_putenv("BC5_DIRECT_RSRC2_JOURNAL=1");
#else
	setenv("BC5_DIRECT_RSRC2_JOURNAL", "1", 1);
#endif
	alignas(16) static uint32_t flat[0x220] = {};
	flat[0x00b] = 0x00000040u; // PS RSRC2 with TRAP_PRESENT, loaded flat
	flat[0x213] = 0x01000000u; // CS RSRC2 with an EXCP_EN bit, loaded flat
	alignas(16) static uint32_t pairs[] = {0x10bu, 0x0u, 0x08bu, 0x00000080u}; // HS clean, GS with EXCP_EN bit 7
	std::vector<uint32_t> ib;
	ib.insert(ib.end(), {0xC0017600u, 0x04bu, 0x0u});            // SET_SH_REG VS RSRC2 = 0
	ib.push_back(0xC0055F00u); put_addr(ib, flat);                 // LOAD_SH_REG, base
	ib.insert(ib.end(), {0x000u, 0x10u, 0x200u, 0x20u});           // (0x000, 16) covers PS; (0x200, 32) covers CS
	ib.push_back(0xC0036300u); put_addr(ib, pairs);                // LOAD_SH_REG_INDEX, pairs
	ib.insert(ib.end(), {0x80000000u, 2u});
	ib.push_back(0xC0036300u); put_addr(ib, flat);                 // LOAD_SH_REG_INDEX, offset format over PS: unread
	ib.insert(ib.end(), {0x00000000u, 0x20u});
	std::vector<bc5::direct::Mapping> m;
	rsrc2_journal(ib.data(), static_cast<uint32_t>(ib.size()), m);
	rsrc2_journal(ib.data(), static_cast<uint32_t>(ib.size()), m); // the same combinations: no new lines
	std::printf("rsrc2test: end\n");
	return 0;
}
'''
open(sys.argv[2], "wb").write(out.encode("utf-8"))
print("ok")
