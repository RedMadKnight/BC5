#!/usr/bin/env python3
"""BC5 experiment 0417, candidate C = candidate B (27b6416f) + tag sdm417 (the save data memory per slot, its
parameters and icon, a call log; all off by default): the private build script p0417f.sh, made from the generated
p0417e.sh by exact replacements. The private tree goes from 0001-new14 (27b6416f) to 0001-new15 (P_NEW15).
usage: mkkit0417f.py <p0417e.sh as generated by mkkit0417e.py> <out dir>"""
import sys

src, out = sys.argv[1:3]
s = open(src, encoding="utf-8", newline="").read()
assert "\r" not in s


def rep(old, new, n=1):
    global s
    assert s.count(old) == n, (old[:70], s.count(old), n)
    s = s.replace(old, new)


rep("# usage: P_NEW14=<patch md5> bash p0417e.sh\n",
    "# usage: P_NEW14=<patch md5> bash p0417e.sh\n"
    "# p0417f (exp 0417, candidate C = B + the save data memory switches, tag sdm417): the private tree goes from\n"
    "# 0001-new14 (27b6416f) to 0001-new15 (P_NEW15). usage: P_NEW15=<patch md5> bash p0417f.sh\n")
rep('[ "$(m "$HERE/0001-new13.patch")" = 05fe48b6 ] && [ "$(m "$HERE/0001-new14.patch")" = "${P_NEW14:?the new patch md5}" ]',
    '[ "$(m "$HERE/0001-new14.patch")" = 27b6416f ] && [ "$(m "$HERE/0001-new15.patch")" = "${P_NEW15:?the new patch md5}" ]')
rep('claim "exp 0417: private rebuild of candidate B (no K1r, the shared backend) under exp0413/p, CPU only" 40',
    'claim "exp 0417: private rebuild of candidate C (B + the save data memory switches) under exp0413/p, CPU only" 40')
rep('done < "$HERE/tree13.md5"\n[ "$bad" = 0 ] || die "$bad files of the private tree are not 05fe48b6\'s"',
    'done < "$HERE/tree14.md5"\n[ "$bad" = 0 ] || die "$bad files of the private tree are not 27b6416f\'s"')
rep('git apply -R --whitespace=nowarn "$HERE/0001-new13.patch" && git apply --whitespace=nowarn "$HERE/0001-new14.patch"',
    'git apply -R --whitespace=nowarn "$HERE/0001-new14.patch" && git apply --whitespace=nowarn "$HERE/0001-new15.patch"')
rep('done < "$HERE/tree14.md5"\n[ "$bad" = 0 ] || die "$bad files differ from the laptop\'s tree"',
    'done < "$HERE/tree15.md5"\n[ "$bad" = 0 ] || die "$bad files differ from the laptop\'s tree"')
rep('echo "tree: $(wc -l < "$HERE/tree14.md5") patched files match the laptop\'s (0001-new14)"',
    'echo "tree: $(wc -l < "$HERE/tree15.md5") patched files match the laptop\'s (0001-new15)"')
rep("BC5_FAULT_RECORD BC5_R3_EOP_STAT BC5_DIRECT_RESET_LABELS_ADD", "BC5_FAULT_RECORD BC5_R3_EOP_STAT BC5_DIRECT_RESET_LABELS_ADD KYTY_BC5_SAVEDATA_MEMORY_SLOTS KYTY_BC5_SAVEDATA_MEMORY_PARAM KYTY_BC5_SAVEDATA_MEMORY_LOG")
open(out + "/p0417f.sh", "w", encoding="utf-8", newline="\n").write(s)
print("p0417f.sh ok")
