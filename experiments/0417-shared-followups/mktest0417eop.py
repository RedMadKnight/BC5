#!/usr/bin/env python3
"""BC5 experiment 0417: OUR test of Codex's EOP-ring claim (the maintainer, 2026-11-13: Codex's remarks are to be
verified, not accepted). The claim: "r3gpu_submit_eop rotates a global ring of 4096 packets; chain_soft_push keeps
the raw address; a deferred callback can read another event's packet after a wrap."

This cuts the REAL text of three things out of a bc5LleAgc.cpp and compiles it with stand-ins for what they call:
  - SoftCp::r3gpu_submit_eop (with its ring, in the old unit)
  - Direct's struct ChainSoft, chain_post_soft_locked and chain_soft_push (and chain_soft_push_copy in the new unit)
Stand-ins: Direct::post puts the callback into a queue that the test runs later (as the completion thread does);
SoftCp::submit records the EOP value the replay reads from its packet; the chain slot is the real field names.
Nothing of Codex's harness is used.

The test, the same for the old unit (patch 01abfc0c: 8f6e92b3) and the new (a099e662 onward: 777eb681):
  T1  one chained EOP with value 1 is pushed and stays deferred; N more are published; then the callbacks run in
      order. Correct: callback i delivers value i. For N = 4095 (no wrap) and N = 4096, 5000, 10000 (a wrap).
  T2  the address the replay was given, old against new: inside the global ring or not.
Expected if the claim is true: the old unit passes N = 4095 and delivers a WRONG value for the first event from
N = 4096 on (the value of the event that reused its slot); the new unit passes all.
usage: mktest0417eop.py <bc5LleAgc.cpp> <out test .cpp>"""
import sys

s = open(sys.argv[1], "rb").read().replace(b"\r\n", b"\n").decode("utf-8")


def cut(start, end="\n}\n"):
    a = s.index(start)
    return s[a:s.index(end, a) + len(end)]


new = "static void chain_soft_push_copy(const uint32_t* dwords, uint32_t n, const char* kind) {" in s
ring = "static uint32_t              g_r3gpu_eop_slots[4096][6];\nstatic std::atomic<uint32_t> g_r3gpu_eop_next {0};\n"
assert (ring in s) != new, "the unit has both or neither of the ring and the owning push"
chain_soft = cut("struct ChainSoft {", "\n};\n")
post_soft = cut("static void chain_post_soft_locked(ChainSlot& s) {")
stat = "static std::atomic<uint64_t> g_eop_stat_pub" in s  # exp 0417's counter (mkeop0417.py)
if stat:
    post_soft = cut("static std::atomic<uint64_t> g_eop_stat_pub", "\n}\n") + cut("static void eop_stat_callback(uint64_t pub) {") + post_soft
push = cut("static void chain_soft_push(const uint32_t* dwords, uint32_t n, const char* kind) {")
push_copy = cut("static void chain_soft_push_copy(const uint32_t* dwords, uint32_t n, const char* kind) {") if new else ""
submit_eop = cut("static void r3gpu_submit_eop(uint64_t eop_value) {")
assert "SoftCp::submit(e.dwords, e.n, e.kind);" in post_soft and "s.soft.push_back(" in push

SRC = r'''// Generated by experiments/0417-shared-followups/mktest0417eop.py: do not edit. GPL-2.0-only.
#include <atomic>
#include <cinttypes>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <functional>
#include <memory>
#include <mutex>
#include <vector>

namespace SoftCp {
struct GpuDone { int v; };
static thread_local std::vector<GpuDone> t_gpu_done;
static std::vector<uint64_t> g_delivered;          // the EOP value each replay read from ITS packet, in callback order
static std::vector<const uint32_t*> g_given;       // the address each replay was given
static void fire_eop(uint64_t v) { g_delivered.push_back(v); }
static void submit(const uint32_t* p, uint32_t n, const char*) { // stand-in for the soft-CP replay: reads the packet as event_write_eop does
	g_given.push_back(p);
	fire_eop(n == 6 && p[0] == 0xc0044700u ? (static_cast<uint64_t>(p[4]) | (static_cast<uint64_t>(p[5]) << 32u)) : ~0ull);
}
enum { kR3EopEvents, kR3EopChained, kR3Count };
static std::atomic<uint64_t> g_r3gpu_count[kR3Count] {};
constexpr uint32_t kR3SeenOther = 320;
static bool r3gpu_first(uint32_t) { return false; }
} // namespace SoftCp
namespace Direct {
static std::vector<std::function<void(bool)>> g_queue; // the completion queue: callbacks run later, in order
static void post(std::function<void(bool failed)> fn) { g_queue.push_back(std::move(fn)); }
static void journal(const char*, ...) {}
static bool chain_cross() { return true; } // BC5_DIRECT_CHAIN=2 on a game thread: the EOP goes to the chain
struct Chain { std::vector<int> segs; };
@CHAIN_SOFT@
struct ChainSlot { // the fields the two functions use, by their real names
	Chain                        c;
	std::mutex                   mu;
	bool                         in_submit = false;
	std::vector<ChainSoft>       soft;
	std::vector<SoftCp::GpuDone> marks;
};
static thread_local ChainSlot g_chain_tl;
@POST_SOFT@
@PUSH@
@PUSH_COPY@
} // namespace Direct
namespace SoftCp {
@RING@
@SUBMIT_EOP@
} // namespace SoftCp

static int g_fail = 0;
static bool run(uint32_t more) {
	Direct::g_queue.clear(); SoftCp::g_delivered.clear(); SoftCp::g_given.clear();
	for (uint64_t v = 1; v <= 1ull + more; v++) SoftCp::r3gpu_submit_eop(v); // each is posted at once: the chain is empty
	if (Direct::g_queue.size() != 1u + more) { std::printf("  setup: %zu callbacks queued, want %u\n", Direct::g_queue.size(), 1u + more); return false; }
	for (auto& f: Direct::g_queue) f(false);
	uint32_t wrong = 0; uint64_t first_got = SoftCp::g_delivered.empty() ? 0 : SoftCp::g_delivered[0];
	for (size_t i = 0; i < SoftCp::g_delivered.size(); i++) wrong += SoftCp::g_delivered[i] != i + 1;
	std::printf("  1 event + %5u more before the callbacks ran: the first callback read value %" PRIu64 " (want 1); %u of %zu callbacks read a wrong value\n", more, first_got, wrong,
	            SoftCp::g_delivered.size());
	return wrong == 0;
}
int main() {
	std::printf("unit: %s\n", @NEW@ ? "NEW (the replay owns a copy)" : "OLD (a global ring of 4096 slots)");
	const bool a = run(4095), b = run(4096), c = run(5000), d = run(10000);
#if @NEW@
	const bool in_ring = false;
#else
	const auto lo = reinterpret_cast<uintptr_t>(&SoftCp::g_r3gpu_eop_slots[0][0]), hi = lo + sizeof(SoftCp::g_r3gpu_eop_slots);
	const auto p  = reinterpret_cast<uintptr_t>(SoftCp::g_given.empty() ? nullptr : SoftCp::g_given[0]);
	const bool in_ring = p >= lo && p < hi;
#endif
	std::printf("  the address a replay was given lies %s the global ring\n", in_ring ? "INSIDE" : "outside");
#if @STAT@
	{ // BC5_R3_EOP_STAT: after run(10000) the first event had 10,000 publications behind it when its callback ran
		const char* e = std::getenv("BC5_R3_EOP_STAT");
		const bool on = e != nullptr && e[0] == '1';
		const uint64_t mx = Direct::g_eop_stat_max.load(), want = on ? 10000u : 0u;
		std::printf("  BC5_R3_EOP_STAT %s: the largest count between a push and its callback is %" PRIu64 " (want %" PRIu64 ")\n", on ? "on" : "off", mx, want);
		if (mx != want) g_fail = 1;
	}
#endif
	std::printf("RESULT no wrap (4095): %s; wrap (4096, 5000, 10000): %s %s %s\n", a ? "correct" : "WRONG", b ? "correct" : "WRONG", c ? "correct" : "WRONG", d ? "correct" : "WRONG");
	if (!(a && b && c && d)) g_fail |= 1;
	return g_fail;
}
'''
out = (SRC.replace("@CHAIN_SOFT@", chain_soft).replace("@POST_SOFT@", post_soft).replace("@PUSH@", push).replace("@PUSH_COPY@", push_copy)
       .replace("@RING@", "" if new else ring).replace("@SUBMIT_EOP@", submit_eop).replace("@NEW@", "1" if new else "0").replace("@STAT@", "1" if (new and stat) else "0"))
if new:
    out = out.replace("static thread_local ChainSlot g_chain_tl;\n", "static thread_local ChainSlot g_chain_tl;\nstatic void chain_soft_push_copy(const uint32_t* dwords, uint32_t n, const char* kind);\n", 1)
open(sys.argv[2], "w", encoding="utf-8", newline="\n").write(out)
print("ok", "new" if new else "old")
